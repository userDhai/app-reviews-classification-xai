"""## 5. Preprocessing"""

import re

def clean_text(text):
    text = str(text)
    text = re.sub(r"http\S+|www\S+", " ", text)
    text = re.sub(r"[^a-zA-Z0-9\s'!?.,-]", " ", text)
    text = text.lower()
    text = re.sub(r'(.)\1{2,}', r'\1\1', text)
    return text.strip()

